export const ACTION_SOURCE = "Kayani Herbs";

function slide(s: Step): ActionSlide {
  return Array.isArray(s) ? { text: s[0], textSw: s[1] } : { title: s.title[0], titleSw: s.title[1], text: s.text[0], textSw: s.text[1] };
}

function card(d: Def): ContentItem {
  const steps = d.steps.map(slide);
  const lines = (sw: boolean) => {
    const L = (b: Bi) => b[sw ? 1 : 0];
    return [
      ...(d.need?.length ? [sw ? "## Mahitaji" : "## You need", ...d.need.map((n) => `• ${L(n)}`)] : []),
      sw ? "## Fanya hivi" : "## Do this",
      ...steps.map((s, i) => {
        const title = sw ? s.titleSw : s.title;
        return `${i + 1}. ${title ? `${title}: ` : ""}${sw ? s.textSw : s.text}`;
      }),
      ...(d.why ? [sw ? "## Kwa nini inafanya kazi" : "## Why it works", L(d.why)] : []),
    ];
  };
  return {
    id: d.id,
    kind: "guide",
    topic: TOPIC_OF[d.challenges[0]],
    title: d.title[0],
    titleSw: d.title[1],
    summary: d.hook[0],
    summarySw: d.hook[1],
    minutes: d.minutes,
    priority: 70,
    tags: [d.type, ...d.challenges, ...(d.tags ?? [])],
    body: lines(false),
    bodySw: lines(true),
    source: ACTION_SOURCE,
    review: "draft",
    fixture: false,
    cover: d.cover,
    ...(d.origin ? { origin: d.origin } : {}),
    action: {
      type: d.type,
      challenges: d.challenges,
      results: d.results,
      ...(d.need ? { need: d.need.map((n) => n[0]), needSw: d.need.map((n) => n[1]) } : {}),
      steps,
      ...(d.why ? { why: d.why[0], whySw: d.why[1] } : {}),
      ...(d.tool ? { tool: d.tool } : {}),
    },
  };
}

